"""
Synthetic Battery Trajectory Generator.
Generates multi-day battery trajectories using the project's Thevenin physical battery model
(backend.simulation.battery.BatteryModel) with realistic power, temperature, and SOC profiles.
"""

import os
import random
import numpy as np
import pandas as pd
from backend.simulation.battery import BatteryModel
from backend.config import Config

SEED = 42

def generate_trajectories(
    n_trajectories: int = 120,
    steps_per_trajectory: int = 96,  # 24 hours at 15-min (0.25h) steps
    output_path: str = "dataset/battery_sim_trajectories.csv"
) -> pd.DataFrame:
    random.seed(SEED)
    np.random.seed(SEED)

    records = []
    ambient_temps = [18.0, 24.0, 30.0, 36.0, 42.0]

    for traj_id in range(n_trajectories):
        # Sample ambient temp with daily diurnal variation
        base_ambient = float(np.random.choice(ambient_temps))
        # Initial SOC randomly between 20% and 90%
        init_soc = float(np.random.uniform(20.0, 90.0))
        
        # Instantiate simulator
        battery = BatteryModel(
            capacity_kwh=Config.BATTERY_CAPACITY_KWH,
            max_power_kw=Config.BATTERY_MAX_POWER_KW,
            efficiency=Config.BATTERY_EFFICIENCY,
            initial_soc=init_soc,
            min_soc=Config.BATTERY_MIN_SOC,
            max_soc=Config.BATTERY_MAX_SOC
        )
        battery.temperature = base_ambient + float(np.random.uniform(-2.0, 3.0))

        # Varied dt for some trajectories to teach dt scaling (mostly 0.25h, some 0.5h or 1.0h)
        if traj_id % 10 == 0:
            dt = 0.5
            n_steps = steps_per_trajectory // 2
        elif traj_id % 20 == 0:
            dt = 1.0
            n_steps = steps_per_trajectory // 4
        else:
            dt = 0.25
            n_steps = steps_per_trajectory

        # Choose profile archetype
        archetype = traj_id % 4
        # 0: Solar self-consumption (charge day, discharge night)
        # 1: Peak shaving (discharge evening peak, charge night)
        # 2: Random walk cycling
        # 3: High C-rate stress test

        for step in range(n_steps):
            hour = (step * dt) % 24.0
            amb_temp = base_ambient + 5.0 * np.sin((hour - 9) * np.pi / 12.0)

            if archetype == 0:
                if 9.0 <= hour <= 15.0:
                    power_kw = -float(np.random.uniform(15.0, 55.0))  # charging
                elif 18.0 <= hour <= 22.0:
                    power_kw = float(np.random.uniform(20.0, 58.0))   # discharging
                else:
                    power_kw = float(np.random.uniform(-5.0, 5.0))    # idle / float
            elif archetype == 1:
                if 17.0 <= hour <= 21.0:
                    power_kw = float(np.random.uniform(30.0, 60.0))
                elif 1.0 <= hour <= 5.0:
                    power_kw = -float(np.random.uniform(20.0, 50.0))
                else:
                    power_kw = float(np.random.uniform(-10.0, 10.0))
            elif archetype == 2:
                power_kw = float(np.random.uniform(-50.0, 50.0))
            else:  # High stress
                power_kw = float(np.random.choice([-60.0, -45.0, 0.0, 45.0, 60.0]))

            soc_prev = battery.soc
            temp_prev = battery.temperature
            actual_power = battery.step(requested_power_kw=power_kw, dt_hours=dt, ambient_temp=amb_temp)
            soc_next = battery.soc
            temp_next = battery.temperature

            records.append({
                "trajectory_id": traj_id,
                "step": step,
                "soc_prev": round(soc_prev, 4),
                "power_kw": round(power_kw, 2),
                "actual_power_kw": round(actual_power, 2),
                "ambient_temp_c": round(amb_temp, 2),
                "dt_hours": dt,
                "temp_prev": round(temp_prev, 2),
                "soc_next": round(soc_next, 4),
                "temp_next": round(temp_next, 2)
            })

    df = pd.DataFrame(records)
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    
    # Write header metadata
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("# Synthetic Battery Simulation Trajectories (Physics-Informed Neural Surrogate)\n")
        f.write(f"# Generated by backend.ai.pinn.generate_battery_data with seed={SEED}\n")
        f.write("# Model: 250 kWh, 60 kW BESS, Thevenin equivalent with Joule heating & cooling\n")
    df.to_csv(output_path, mode="a", index=False)
    print(f"Generated {len(df)} trajectory steps across {n_trajectories} trajectories -> {output_path}")
    return df

if __name__ == "__main__":
    generate_trajectories()

